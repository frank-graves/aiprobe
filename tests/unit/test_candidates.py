"""Offline tests for declarative candidate generation."""

from __future__ import annotations

from aiprobe.detectors.candidates import (
    extract_paths_from_html,
    generate_candidates,
)
from aiprobe.models.profile import AntibotType
from aiprobe.providers.base import ProviderSpec


def test_generate_candidates_without_spec() -> None:
    candidates = generate_candidates(None)
    assert len(candidates) > 0
    assert any(
        c.path == "/api/v1/chat" and c.method == "POST" and c.source == "pattern"
        for c in candidates
    )


def test_generate_candidates_with_spec() -> None:
    spec = ProviderSpec(
        name="test",
        domains=["example.com"],
        candidate_endpoints={"chat": "/custom/chat"},
        expected_antibot=AntibotType.NONE,
    )
    candidates = generate_candidates(spec)

    custom = next(c for c in candidates if c.path == "/custom/chat")
    assert custom.source == "provider"
    assert custom.method == "POST"


def test_deduplication() -> None:
    # /api/v1/chat is generated by pattern, but let's add it via provider too
    spec = ProviderSpec(
        name="test",
        domains=["example.com"],
        candidate_endpoints={"chat": "/api/v1/chat"},
        expected_antibot=AntibotType.NONE,
    )
    candidates = generate_candidates(spec)

    matches = [c for c in candidates if c.path == "/api/v1/chat" and c.method == "POST"]
    assert len(matches) == 1
    assert matches[0].source == "provider"  # Provider should win


def test_extract_paths_from_html() -> None:
    html = """
    <script src="/static/app.js"></script>
    <script>
        fetch("/api/v1/chat?session=123");
        fetch("/v1/models");
    </script>
    <link rel="stylesheet" href="/styles/main.css">
    """
    paths = extract_paths_from_html(html)

    assert "/api/v1/chat" in paths  # Query string stripped
    assert "/v1/models" in paths
    assert "/static/app.js" not in paths  # Static extension ignored
    assert "/styles/main.css" not in paths  # Static extension ignored
